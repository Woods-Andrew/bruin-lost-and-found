import { cacheKey, readCache, writeCache } from "@/lib/ai/cache";
import { runWithRetry } from "@/lib/jobs/queue";
import { config, visionConfigured } from "@/lib/config";
import { logError } from "@/lib/log";
import type { ItemAttributes, VisionResult } from "@/lib/types";

const MOCK_NOTE =
  "Mock vision (no Qwen vision endpoint configured). This is not real model inference — edit the fields before publishing.";

function emptyAttributes(): ItemAttributes {
  return {
    category: "unknown",
    color: "unknown",
    brand: "unknown",
    material: "unknown",
    distinctiveMarks: "none noted",
  };
}

function mockVision(): VisionResult {
  return {
    title: "Unidentified item — please edit",
    description:
      "A personal item photographed for Bruin Lost and Found. Replace this mock description with what you actually see in the photo.",
    attributes: emptyAttributes(),
    source: "mock",
    note: MOCK_NOTE,
  };
}

function parseVision(content: string): Omit<VisionResult, "source" | "note"> {
  const jsonStart = content.indexOf("{");
  const jsonEnd = content.lastIndexOf("}");
  const parsed = JSON.parse(content.slice(jsonStart, jsonEnd + 1)) as {
    title?: string;
    description?: string;
    attributes?: Partial<ItemAttributes>;
  };
  return {
    title: parsed.title || "Found item",
    description: parsed.description || content,
    attributes: { ...emptyAttributes(), ...parsed.attributes },
  };
}

async function callVision(imageBase64: string, mimeType: string): Promise<VisionResult> {
  const url = `${config.visionUrl.replace(/\/$/, "")}/v1/chat/completions`;
  const response = await fetch(url, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${config.qwenApiKey}`,
    },
    body: JSON.stringify({
      model: config.visionModel,
      temperature: 0.2,
      messages: [
        {
          role: "system",
          content:
            "You catalog lost-and-found photos. Return JSON with title, description, and attributes {category, color, brand, material, distinctiveMarks}.",
        },
        {
          role: "user",
          content: [
            {
              type: "text",
              text: "Describe this item for a university lost and found listing.",
            },
            {
              type: "image_url",
              image_url: { url: `data:${mimeType};base64,${imageBase64}` },
            },
          ],
        },
      ],
    }),
  });
  if (!response.ok) {
    throw new Error(`Vision endpoint ${response.status}: ${await response.text()}`);
  }
  const body = (await response.json()) as {
    choices?: { message?: { content?: string } }[];
  };
  const content = body.choices?.[0]?.message?.content || "{}";
  return {
    ...parseVision(content),
    source: "qwen",
    note: "Generated by the configured Qwen vision-language endpoint. Review before publishing.",
  };
}

export async function analyzePhoto(imageBase64: string, mimeType: string) {
  const key = cacheKey("vision", `${mimeType}:${imageBase64}`);
  const cached = await readCache<VisionResult>(key);
  if (cached) return { ...cached, note: `${cached.note} (cached)` };

  if (!visionConfigured()) {
    const result = mockVision();
    await writeCache(key, "vision", result);
    return result;
  }

  try {
    const result = await runWithRetry("vision", () => callVision(imageBase64, mimeType));
    await writeCache(key, "vision", result);
    return result;
  } catch (error) {
    await logError("vision", error);
    return {
      ...mockVision(),
      note: "Vision endpoint failed after retries. Showing a labeled mock so you can still publish manually. This is not real inference.",
    };
  }
}
